/* Byte 0 of every frame in both directions is a throwaway dummy: STM32 hardware-NSS SPI
 * slave mode is known to unreliably capture/shift out the very first byte right after NSS
 * asserts (the shift register isn't guaranteed armed in time for the first clock edge), so
 * real data is placed starting at byte 1 to keep that unreliable byte out of the way.
 *
 * request:  frame[0]=dummy, frame[1]=SPI_SYNC_BYTE, frame[2]=command, frame[3]=argument,
 *           frame[4]=checksum (XOR of frame[1..3])
 * response: resp[0]=dummy,  resp[1]=SPI_ACK_BYTE,   resp[2]=command echoed, resp[3]=argument applied,
 *           resp[4]=status (1=ok), resp[5]=checksum (XOR of resp[1..4])
 * The checksum lets each side reject a frame that was electrically corrupted in transit, instead of
 * mistaking garbage for a valid sync/ack marker. */
static void Process_SPI_Command(const uint8_t *frame, uint8_t *response)
{
  memset(response, 0, SPI_FRAME_LEN);

  uint8_t frame_checksum = frame[1] ^ frame[2] ^ frame[3];
  if (frame[1] != SPI_SYNC_BYTE || frame[4] != frame_checksum)
  {
    return;
  }

  uint8_t status = 0U;
  if (frame[2] == CMD_SET_LED)
  {
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, frame[3] != 0U ? GPIO_PIN_SET : GPIO_PIN_RESET);
    status = 1U;
  }

  response[1] = SPI_ACK_BYTE;
  response[2] = frame[2];
  response[3] = frame[3];
  response[4] = status;
  response[5] = response[1] ^ response[2] ^ response[3] ^ response[4];
}

